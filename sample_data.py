def get_all_destinations_df() -> Any:
    """Returns all tourist destinations as a Pandas DataFrame."""
    if pd is not None:
        return pd.DataFrame(DESTINATIONS_DATA)
    return DESTINATIONS_DATA

def get_all_attractions_df() -> Any:
    """Returns all attractions as a Pandas DataFrame."""
    if pd is not None:
        return pd.DataFrame(ATTRACTIONS_DATA)
    return ATTRACTIONS_DATA

def get_all_guides_df() -> Any:
    """Returns all local guides as a Pandas DataFrame."""
    if pd is not None:
        return pd.DataFrame(GUIDES_DATA)
    return GUIDES_DATA

def get_destination_by_id(dest_id: str) -> Dict[str, Any]:
    """Retrieves single destination dictionary by unique ID or name."""
    dest_id_clean = dest_id.strip().lower()
    for d in DESTINATIONS_DATA:
        if d["id"] == dest_id_clean or d["name"].lower() == dest_id_clean:
            return d
    return DESTINATIONS_DATA[0]

def get_attractions_for_destination(dest_id: str) -> List[Dict[str, Any]]:
    """Retrieves list of attractions belonging to a destination."""
    dest_id_clean = dest_id.strip().lower()
    return [a for a in ATTRACTIONS_DATA if a["destination_id"] == dest_id_clean]
